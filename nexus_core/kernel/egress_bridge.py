"""Rootless egress bridge: netns shell whose only exit is the scope proxy.

The shell runs inside a network namespace created by ``bwrap --unshare-net``,
so it has no route to anything (not even the host loopback). A UNIX socket is
bind-mounted into the namespace and two ``socat`` processes bridge it to the
running :class:`nexus_core.kernel.egress.Socks5EgressProxy` on the host:

* host:   ``socat UNIX-LISTEN:<sock>,fork TCP:127.0.0.1:<proxy_port>``
* sandbox: ``socat TCP-LISTEN:1080,fork UNIX-CONNECT:/run/egress.sock``

Two details that the naive version gets wrong and this module fixes:

* ``--ro-bind / /`` makes ``/run`` read-only, so bwrap cannot create the mount
  point (``Can't create file /run/egress.sock: Read-only file system``). The
  command mounts a writable ``--tmpfs /run`` before the bind.
* A backgrounded ``socat`` survives a shell that exits without a trap. The
  sandbox runs with ``--unshare-pid`` (all its processes die with PID 1) *and*
  the launcher traps ``EXIT`` to kill the listener; the orphan test checks both.

Every command runs under ``proxychains4`` (see ``build_bwrap_cmd``): the
``LD_PRELOAD`` is inherited by children, so ``bash -c "nmap …"`` and any other
nested invocation are covered too. Static binaries that ignore the preload
simply have no network in the namespace (fail closed), and raw-socket scans
(``nmap -sS``, UDP, ``-O``) do not work through a SOCKS5 proxy by design.
"""

from __future__ import annotations

import asyncio
import shlex
import shutil
import tempfile
from contextlib import suppress
from pathlib import Path
from typing import Self

#: Path the sandbox sees for the bind-mounted bridge socket.
SANDBOX_SOCKET = "/run/egress.sock"
#: Loopback port the in-sandbox socat listens on.
SANDBOX_PROXY_PORT = 1080
#: Default port of the host-side :class:`Socks5EgressProxy`.
DEFAULT_PROXY_PORT = 1080
#: How long ``start`` waits for the host socat to create its socket.
BRIDGE_READY_TIMEOUT = 5.0
#: How long ``stop`` waits for the host socat to exit before killing it.
STOP_TIMEOUT = 5.0
#: Opt-in switch the shell handler reads before routing a command here.
ISOLATION_ENV = "NEXUS_SHELL_ISOLATION"
ISOLATION_MODE = "egress"
#: Private HOME inside the namespace (the real one is read-only).
SANDBOX_HOME = "/tmp/omni-home"
#: Config proxychains reads inside the namespace.
SANDBOX_PROXYCHAINS_CONF = "/tmp/omni-proxychains.conf"
#: proxychains config for the in-namespace listener. No credentials live here.
PROXYCHAINS_CONFIG = (
    "# generated by OMNI for this invocation (no credentials in this file)\n"
    "strict_chain\n"
    "quiet_mode\n"
    "proxy_dns\n"
    "remote_dns_subnet 224\n"
    "tcp_read_time_out 15000\n"
    "tcp_connect_time_out 8000\n"
    "[ProxyList]\n"
    f"socks5 127.0.0.1 {SANDBOX_PROXY_PORT}\n"
)



class EgressBridgeUnavailable(RuntimeError):
    """The bridge cannot be offered: a dependency or the host proxy is missing."""


def bridge_available() -> bool:
    """Whether ``bwrap`` and ``socat`` are installed on this machine."""
    return bool(shutil.which("bwrap") and shutil.which("socat"))


def proxychains_available() -> bool:
    """Whether a ``proxychains`` binary exists for the wrapped command."""
    return bool(shutil.which("proxychains4") or shutil.which("proxychains"))


class EgressBridge:
    """One host-side socat plus the bwrap argv that consumes it.

    ``proxy_port`` is the port of an **already running** ``Socks5EgressProxy``
    (see :func:`nexus_core.kernel.egress.proxy_for_scope`); this class does not
    start or authorize the proxy itself, it only carries bytes.
    """

    def __init__(
        self,
        proxy_port: int = DEFAULT_PROXY_PORT,
        *,
        proxy_host: str = "127.0.0.1",
        sandbox_proxy_port: int = SANDBOX_PROXY_PORT,
        socket_path: Path | str | None = None,
    ) -> None:
        self.proxy_host = str(proxy_host)
        self.proxy_port = int(proxy_port)
        self.sandbox_proxy_port = int(sandbox_proxy_port)
        #: Injected by tests; ``start`` creates a private directory otherwise.
        self._injected_socket = Path(socket_path) if socket_path is not None else None
        #: Injected sockets are usable before ``start`` so the argv can be built
        #: (and asserted) without spawning a process.
        self._socket_path: Path | None = self._injected_socket
        self._directory: tempfile.TemporaryDirectory[str] | None = None
        self._process: asyncio.subprocess.Process | None = None

    @property
    def socket_path(self) -> Path | None:
        """Host path of the bridge socket (``None`` before ``start``)."""
        return self._socket_path

    @property
    def proxy_url(self) -> str:
        """SOCKS URL the sandbox sees (always the in-namespace listener)."""
        return f"socks5h://127.0.0.1:{self.sandbox_proxy_port}"

    async def start(self) -> EgressBridge:
        """Create the private directory and the host-side socat."""
        if self._process is not None:
            return self
        bwrap_path = shutil.which("bwrap")
        socat_path = shutil.which("socat")
        if bwrap_path is None or socat_path is None:
            missing = "bwrap" if bwrap_path is None else "socat"
            raise EgressBridgeUnavailable(
                f"{missing} is not installed: the isolated shell needs both "
                "bubblewrap and socat (apt install bubblewrap socat)."
            )
        if self._injected_socket is not None:
            self._socket_path = self._injected_socket
        else:
            directory = tempfile.TemporaryDirectory(prefix="omni-egress-")
            self._directory = directory
            self._socket_path = Path(directory.name) / "egress.sock"
        try:
            self._process = await asyncio.create_subprocess_exec(
                socat_path,
                f"UNIX-LISTEN:{self._socket_path},mode=0600,fork",
                f"TCP:{self.proxy_host}:{self.proxy_port}",
                stdin=asyncio.subprocess.DEVNULL,
                stdout=asyncio.subprocess.DEVNULL,
                stderr=asyncio.subprocess.PIPE,
            )
            await self._await_socket()
        except BaseException:
            await self.stop()
            raise
        return self

    async def _await_socket(self) -> None:
        """Wait until socat created the socket, failing fast if it exited."""
        loop = asyncio.get_running_loop()
        deadline = loop.time() + BRIDGE_READY_TIMEOUT
        assert self._socket_path is not None
        while loop.time() < deadline:
            process = self._process
            if process is not None and process.returncode is not None:
                detail = ""
                if process.stderr is not None:
                    detail = (await process.stderr.read()).decode("utf-8", "replace").strip()
                raise EgressBridgeUnavailable(
                    "the host socat exited before the bridge was ready"
                    + (f": {detail}" if detail else "")
                )
            if self._socket_path.exists():
                return
            await asyncio.sleep(0.02)
        raise EgressBridgeUnavailable(
            f"the host socat did not create {self._socket_path} "
            f"within {BRIDGE_READY_TIMEOUT:.0f}s"
        )

    async def stop(self) -> None:
        """Terminate the host socat and remove the private directory."""
        process, self._process = self._process, None
        if process is not None and process.returncode is None:
            process.terminate()
            try:
                await asyncio.wait_for(process.wait(), STOP_TIMEOUT)
            except TimeoutError:
                process.kill()
                await process.wait()
        if self._directory is not None:
            self._directory.cleanup()
            self._directory = None
        self._socket_path = None

    async def __aenter__(self) -> Self:
        return await self.start()

    async def __aexit__(self, *exc_info: object) -> None:
        await self.stop()

    def build_bwrap_cmd(self, command: str, *, proxychains: bool = False,
                        workspace: str | Path | None = None) -> list[str]:
        """Argv that runs ``command`` with no network except the bridge.

        The command is the *last* line of the launcher script, so it is the
        sandbox's foreground process: its exit code is the one bwrap returns.
        ``proxychains=True`` wraps the command for tools that ignore
        ``ALL_PROXY``; ``workspace`` is bound read-write (the root bind is
        read-only, so without it the shell could not write its loot).
        """
        if not str(command or "").strip():
            raise ValueError("command must not be empty")
        if self._socket_path is None:
            raise EgressBridgeUnavailable("start() the bridge before building the command")
        bwrap_path = shutil.which("bwrap")
        if bwrap_path is None:
            raise EgressBridgeUnavailable("bwrap is not installed: apt install bubblewrap")
        workspace_path: Path | None = None
        if workspace is not None:
            candidate = Path(workspace).resolve()
            if not candidate.is_dir():
                raise ValueError(f"workspace does not exist: {candidate}")
            workspace_path = candidate
        port = self.sandbox_proxy_port
        inner = str(command)
        if proxychains:
            proxychains_bin = shutil.which("proxychains4") or shutil.which("proxychains")
            if proxychains_bin is None:
                raise EgressBridgeUnavailable(
                    "proxychains4 is not installed: tools that ignore ALL_PROXY "
                    "cannot reach the network without it"
                )
            inner = (
                f"{proxychains_bin} -f {SANDBOX_PROXYCHAINS_CONF} "
                f"bash -c {shlex.quote(str(command))}"
            )
        launcher_lines = [f"mkdir -p {SANDBOX_HOME}"]
        if proxychains:
            launcher_lines += [
                f"cat > {SANDBOX_PROXYCHAINS_CONF} <<'EOF'",
                PROXYCHAINS_CONFIG.rstrip("\n"),
                "EOF",
            ]
        launcher_lines += [
            f"socat TCP-LISTEN:{port},fork,reuseaddr UNIX-CONNECT:{SANDBOX_SOCKET} &",
            "spid=$!",
            "trap 'kill $spid 2>/dev/null' EXIT INT TERM",
            "for _ in $(seq 1 100); do",
            (
                f"  (exec 3<>/dev/tcp/127.0.0.1/{port}) 2>/dev/null "
                "&& { exec 3>&-; break; }"
            ),
            "  sleep 0.02",
            "done",
            inner,
        ]
        launcher = "\n".join(launcher_lines)
        return [
            bwrap_path,
            # No route at all, and no process may outlive PID 1.
            "--unshare-net",
            "--unshare-pid",
            "--die-with-parent",
            "--ro-bind", "/", "/",
            "--dev", "/dev",
            "--proc", "/proc",
            # /run is read-only under the root bind; the mount point needs it rw.
            "--tmpfs", "/run",
            "--tmpfs", "/tmp",
            *(
                ["--bind", str(workspace_path), str(workspace_path)]
                if workspace_path is not None else []
            ),
            "--bind", str(self._socket_path), SANDBOX_SOCKET,
            "--setenv", "HOME", SANDBOX_HOME,
            # A socks5 URL for both families: an ``http://`` value here would
            # make curl speak HTTP CONNECT to a SOCKS server.
            "--setenv", "ALL_PROXY", self.proxy_url,
            "--setenv", "HTTP_PROXY", self.proxy_url,
            "--setenv", "HTTPS_PROXY", self.proxy_url,
            "--setenv", "NO_PROXY", "",
            "bash", "-c", launcher,
        ]

    async def run(
        self,
        command: str,
        *,
        cwd: str | Path | None = None,
        timeout: float = 300.0,
        proxychains: bool = False,
        workspace: str | Path | None = None,
    ) -> tuple[str, str, int | None]:
        """Run ``command`` isolated; return ``(stdout, stderr, exit_code)``."""
        if self._process is None:
            await self.start()
        argv = self.build_bwrap_cmd(
            command, proxychains=proxychains, workspace=workspace
        )
        process = await asyncio.create_subprocess_exec(
            *argv,
            cwd=str(cwd) if cwd is not None else None,
            stdin=asyncio.subprocess.DEVNULL,
            stdout=asyncio.subprocess.PIPE,
            stderr=asyncio.subprocess.PIPE,
        )
        try:
            stdout, stderr = await asyncio.wait_for(process.communicate(), timeout=timeout)
        except BaseException:
            with suppress(ProcessLookupError):
                process.kill()
            with suppress(Exception):
                await process.wait()
            raise
        return (
            stdout.decode("utf-8", "replace"),
            stderr.decode("utf-8", "replace"),
            process.returncode,
        )


